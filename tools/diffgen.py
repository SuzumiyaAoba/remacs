def seed(name: str, call: int) -> int:
    h = int.from_bytes(hashlib.sha256(name.encode()).digest()[:8], "big")
    return (h + call * 7919) % (1 << 62)


def corpus_at(seedv: int, k: int) -> str:
    return CORPUS[(seedv >> (k * 7)) % N_CORPUS]


def make_call(name: str, n: int, call: int) -> str:
    parts = ["(" + name]
    for k in range(n):
        parts.append(corpus_at(seed(name, call), k))
    return " ".join(parts) + ")"


