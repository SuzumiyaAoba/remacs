DYNAMIC_SKIP = set()
_p = Path('tests/diff/skip-dynamic.txt')
if _p.exists():
    DYNAMIC_SKIP = set(_p.read_text().split())

def main() -> None:
    gnu = (DIFF / "subrs.gnu.txt").read_text().splitlines()
    remacs_path = DIFF / "subrs.remacs.txt"
    remacs = set()
    if remacs_path.exists():
        remacs = {l.split("|")[0] for l in remacs_path.read_text().splitlines()}

    forms = []
    idx = 0
    for line in gnu:
        parts = line.split("|")
        name, mn, mx, sf = parts[0], parts[1], parts[2], parts[3]
        if sf == "1":
            continue
        if name in SKIP_EXACT:
            continue
        if any(name.startswith(p) for p in SKIP_PREFIX):
            continue
        if remacs and name not in remacs:
            continue
        if name in DYNAMIC_SKIP:
            continue
        mn_i = int(mn)
        mx_i = 1024 if mx in ("M", "U") else int(mx)
        calls = []
        calls.append(make_call(name, mn_i, 0))
        calls.append(make_call(name, mn_i, 1))
        if mn_i > 0:
            calls.append("(" + name + ")")
        if mx_i < 10:
            calls.append(make_call(name, mx_i + 1, 2))
        body = (
            '(with-temp-buffer (insert "a\\\\nb\\\\nc\\\\n") '
            "(goto-char 5) " + make_call(name, mn_i, 3) + ")"
        )
        calls.append(body)
        for c in calls:
            idx += 1
            forms.append("    (%d %s)" % (idx, c))
    driver = RUNNER.replace("%FORMS%", "\n".join(forms))
    (DIFF / "driver.el").write_text(driver)
    print(f"{idx} forms -> {DIFF/'driver.el'}")


if __name__ == "__main__":
    main()
